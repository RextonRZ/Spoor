import { chromium } from "playwright";
const out = process.argv[2];
const b = await chromium.launch();
const errors = [];
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
p.on("console", (m) => m.type() === "error" && errors.push(m.text()));
p.on("pageerror", (e) => errors.push(String(e)));
await p.goto("http://localhost:3000/operator", { waitUntil: "networkidle" });
await p.waitForTimeout(1500);
await p.screenshot({ path: `${out}/settings_data.png` });
await p.getByRole("tab", { name: /Cameras/ }).click(); await p.waitForTimeout(500);
await p.screenshot({ path: `${out}/settings_cams.png` });
await p.getByRole("tab", { name: /Models/ }).click(); await p.waitForTimeout(500);
await p.screenshot({ path: `${out}/settings_models.png` });
const ph = await b.newPage({ viewport: { width: 390, height: 844 } });
await ph.goto("http://localhost:3000/operator", { waitUntil: "networkidle" }); await ph.waitForTimeout(1200);
console.log("phone overflow px:", await ph.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth));
await b.close();
console.log("console errors:", errors.length ? errors.slice(0, 3) : "none");
