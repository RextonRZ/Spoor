import { chromium } from "playwright";
const out = process.argv[2];
const b = await chromium.launch();
const errors = [];
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
p.on("console", (m) => m.type() === "error" && errors.push(m.text()));
await p.goto("http://localhost:3000/cases", { waitUntil: "networkidle" });
await p.waitForTimeout(2000);
await p.screenshot({ path: `${out}/cases.png` });
await p.getByRole("tab", { name: /Resolved/ }).click();
await p.waitForTimeout(400);
await p.screenshot({ path: `${out}/cases_resolved.png`, clip: { x: 240, y: 0, width: 1200, height: 460 } });
const ph = await b.newPage({ viewport: { width: 390, height: 844 } });
await ph.goto("http://localhost:3000/cases", { waitUntil: "networkidle" });
await ph.waitForTimeout(2000);
await ph.screenshot({ path: `${out}/cases_phone.png` });
console.log("phone overflow px:", await ph.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth));
await b.close();
console.log("console errors:", errors.length ? errors.slice(0, 3) : "none");
