// Generates TypeScript types from the backend's exported JSON Schemas (backend/schemas/*.schema.json, step 01).
// One file per schema keeps shared $defs (e.g. TimeWindow) from colliding; index.ts re-exports the top-level types.
//   npm run gen:types        (run `uv run python scripts/export_schemas.py` in backend/ first if contracts changed)
import { readdirSync, readFileSync, mkdirSync, writeFileSync, rmSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "..", "backend", "schemas");
const out = join(root, "src", "contracts", "generated");
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
const names = [];
for (const file of readdirSync(src).filter((f) => f.endsWith(".schema.json")).sort()) {
  const name = file.replace(".schema.json", "");
  const schema = JSON.parse(readFileSync(join(src, file), "utf8"));
  const ts = await compile(schema, name, {
    bannerComment: `/* Generated from backend/schemas/${file} by scripts/gen-types.mjs. Do not edit. */`,
    additionalProperties: false,
    strictIndexSignatures: true,
    unreachableDefinitions: false,
    format: false,
  });
  writeFileSync(join(out, `${name}.ts`), ts);
  names.push(name);
}
writeFileSync(join(out, "index.ts"),
  "/* Generated by scripts/gen-types.mjs. Do not edit. */\n" +
  names.map((n) => `export type { ${n} } from "./${n}";`).join("\n") + "\n");
console.log(`generated ${names.length} contract types into src/contracts/generated`);
